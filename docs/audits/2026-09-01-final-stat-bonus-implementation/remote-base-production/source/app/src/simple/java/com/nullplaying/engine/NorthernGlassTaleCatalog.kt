    private fun chapter(
        number: Int,
        title: String,
        subtitle: String,
        opening: String,
        ending: String,
        hook: String,
        vararg acts: TaleActDefinition,
    ) = AdventureTaleDefinition(
        id = "ash_border.c${number.toString().padStart(2, '0')}",
        kind = TaleKind.MAIN,
        volumeNumber = 2,
        chapterNumber = number,
        title = title,
        subtitle = subtitle,
        openingTemplate = opening,
        endingTemplate = ending,
        nextHookTemplate = hook,
        acts = acts.mapIndexed { index, act ->
            act.copy(target = AdventureTaleCatalog.mainActTarget(number, index))
        },
        nextId = if (number < 24) {
            "ash_border.c${(number + 1).toString().padStart(2, '0')}"
        } else {
            null
        },
    )

    private fun act(
        id: String,
        title: String,
        body: String,
        completion: String,
    ) = TaleActDefinition(
        id = id,
        titleTemplate = title,
        bodyTemplate = body,
        completionTemplate = completion,
        target = 1L,
    )
