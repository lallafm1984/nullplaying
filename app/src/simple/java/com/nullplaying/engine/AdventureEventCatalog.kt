                }
        }) { "Every event needs three uniquely identified approaches with one to three compatible signals." }
        AdventureBehaviorSignal.values().forEach { signal ->
            val diversityKeys = all.filter { event ->
                event.approaches.any { signal in it.behaviorSignals }
            }.map { event -> "${event.context}:${event.storyFamily}" }.toSet()
            require(diversityKeys.size >= 3) {
                "Behavior signal $signal needs at least three distinct context/story-family sources."
            }
        }
        require(all.filter { event ->
            event.approaches.any { TAKE_RISK in it.behaviorSignals }
        }.all { event ->
            event.approaches.any { TAKE_RISK !in it.behaviorSignals }
        }) { "Every risk-bearing event needs a non-risk baseline approach." }

        val expectedContexts = mapOf(
            OUTBOUND_ROUTE to 18,
            FIELD_EXPLORATION to 22,
            PRE_COMBAT to 15,
            POST_COMBAT to 15,
            RETURN_ROUTE to 15,
            TOWN_RETURN to 15,
        )
        require(all.groupingBy { it.context }.eachCount() == expectedContexts) {
            "Adventure event context allocation does not match the authored 18/22/15/15/15/15 split."
        }
        require(all.all { event ->
            with(event.rewardWeights) { experience + gold + item + route == 100 }
        }) { "Every event reward profile must total 100." }
        require(all.sumOf { it.rewardWeights.item } == 2_500) {
            "The catalog item reward weight must average exactly 25%."
        }

        val battleEvents = all.filter { it.battleRule != null }
        require(battleEvents.size in 12..15) { "The catalog needs 12 to 15 incident-battle events." }
        require(battleEvents.all { event ->
            val rule = requireNotNull(event.battleRule)
            listOf(rule.successGrade, rule.partialGrade, rule.failureGrade).any { it == null }
        }) { "Incident battles must leave at least one non-battle outcome." }
        val battleGrades = battleEvents.flatMap { event ->
            val rule = requireNotNull(event.battleRule)
            listOfNotNull(rule.successGrade, rule.partialGrade, rule.failureGrade)
        }.toSet()
        require(ELITE in battleGrades && BOSS in battleGrades) {
            "Incident battles must include both elite and boss outcomes."
        }
    }
