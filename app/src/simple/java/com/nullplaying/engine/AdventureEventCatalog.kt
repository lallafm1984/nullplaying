    private fun a(
        id: String,
        ko: String,
        en: String,
        ja: String,
        primary: AdventureEventStat,
        secondary: AdventureEventStat,
        vararg signals: AdventureBehaviorSignal,
    ) = AdventureEventApproach(
        id = id,
        title = t(ko, en, ja),
        primaryStat = primary,
        secondaryStat = secondary,
        behaviorSignals = signals.toSet(),
    )

    private fun w(experience: Int, gold: Int, item: Int, route: Int) =
        AdventureEventRewardWeights(experience, gold, item, route)

    private fun weightsFor(context: AdventureEventContext): AdventureEventRewardWeights = when (context) {
        OUTBOUND_ROUTE -> w(20, 15, 25, 40)
        FIELD_EXPLORATION -> w(35, 15, 25, 25)
        PRE_COMBAT -> w(35, 15, 25, 25)
        POST_COMBAT -> w(35, 25, 25, 15)
        RETURN_ROUTE -> w(20, 25, 25, 30)
        TOWN_RETURN -> w(20, 45, 25, 10)
    }

    private fun goldFor(context: AdventureEventContext): Long = when (context) {
        TOWN_RETURN -> 20L
        RETURN_ROUTE, POST_COMBAT -> 15L
        else -> 10L
    }

    private fun routeFor(context: AdventureEventContext): Long = when (context) {
        OUTBOUND_ROUTE -> -2_000L
        FIELD_EXPLORATION, PRE_COMBAT -> -1_500L
        POST_COMBAT, RETURN_ROUTE, TOWN_RETURN -> -1_000L
    }

    private fun event(
        id: String,
        title: AdventureText,
        scene: AdventureText,
        approaches: List<AdventureEventApproach>,
        success: AdventureText,
        partial: AdventureText,
        failure: AdventureText,
        itemName: AdventureText,
        context: AdventureEventContext,
        storyFamily: String,
        battleRule: AdventureEventBattleRule? = null,
        successGoldPerLevel: Long = goldFor(context),
        successRouteDelayMillis: Long = routeFor(context),
        rewardWeights: AdventureEventRewardWeights = weightsFor(context),
    ) = AdventureEventDefinition(
        id = id,
        title = title,
        scene = scene,
        approaches = approaches,
        success = success,
        partial = partial,
        failure = failure,
        itemName = itemName,
        successItem = AdventureEventItemReward.EQUIPMENT,
        successGoldPerLevel = successGoldPerLevel,
        successRouteDelayMillis = successRouteDelayMillis,
        rewardWeights = rewardWeights,
        context = context,
        storyFamily = storyFamily,
        battleRule = battleRule,
    )

